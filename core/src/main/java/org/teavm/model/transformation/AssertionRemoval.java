package org.teavm.model.transformation;

import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.function.Predicate;
import org.teavm.model.BasicBlock;
import org.teavm.model.ClassReader;
import org.teavm.model.ClassReaderSource;
import org.teavm.model.ElementModifier;
import org.teavm.model.FieldReader;
import org.teavm.model.FieldReference;
import org.teavm.model.Instruction;
import org.teavm.model.ListableClassReaderSource;
import org.teavm.model.MethodDescriptor;
import org.teavm.model.MethodReader;
import org.teavm.model.MethodReference;
import org.teavm.model.Phi;
import org.teavm.model.Program;
import org.teavm.model.ValueType;
import org.teavm.model.Variable;
import org.teavm.model.VariableReader;
import org.teavm.model.instructions.AbstractInstructionReader;
import org.teavm.model.instructions.BranchingInstruction;
import org.teavm.model.instructions.GetFieldInstruction;
import org.teavm.model.instructions.IntegerConstantInstruction;
import org.teavm.model.instructions.InvokeInstruction;
import org.teavm.model.util.DefinitionExtractor;
import org.teavm.model.util.ProgramUtils;
import org.teavm.model.util.TransitionExtractor;

/**
 * Removes assertions from code. Must run after the set of reachable classes is known.
 *
 * <p>First, {@link #analyze(ListableClassReaderSource, Predicate)} looks for static final boolean fields
 * that are written exactly once, in the static initializer of their declaring class, with a value derived from
 * the result of {@link Class#desiredAssertionStatus()} (i.e. {@code $assertionsDisabled} generated by javac,
 * or {@code ENABLED} field of Kotlin's {@code _Assertions}). The value of such field is evaluated
 * under assumption that {@code desiredAssertionStatus} returns {@code false}.</p>
 *
 * <p>Then, {@link #apply(Program)} replaces reads of these fields with constants and calls to
 * {@code desiredAssertionStatus} with {@code false}. Subsequent optimizations remove branches
 * that check assertions.</p>
 */
public class AssertionRemoval {
    private static final MethodReference ASSERTION_METHOD = new MethodReference(Class.class, "desiredAssertionStatus",
            boolean.class);
    private static final MethodDescriptor CLINIT = new MethodDescriptor("<clinit>", void.class);

    private final ClassReaderSource classSource;
    private final Map<FieldReference, Optional<FieldReference>> resolvedFields = new HashMap<>();
    private final Map<FieldReference, Integer> fieldValues = new LinkedHashMap<>();

    public AssertionRemoval(ClassReaderSource classSource) {
        this.classSource = classSource;
    }

    public void analyze(ListableClassReaderSource classes, Predicate<MethodReference> methodFilter) {
        var invalidFields = new HashSet<FieldReference>();
        for (var className : classes.getClassNames()) {
            var cls = classes.get(className);
            if (cls == null) {
                continue;
            }
            for (var method : cls.getMethods()) {
                if (method.getProgram() == null || !methodFilter.test(method.getReference())) {
                    continue;
                }
                analyzeMethod(cls, method, invalidFields);
            }
        }
        fieldValues.keySet().removeAll(invalidFields);
    }

    private void analyzeMethod(ClassReader cls, MethodReader method, Set<FieldReference> invalidFields) {
        var program = method.getProgram();
        var reader = new AbstractInstructionReader() {
            Program writableProgram;

            @Override
            public void putField(VariableReader instance, FieldReference fieldRef, VariableReader value,
                    ValueType fieldType) {
                if (instance != null) {
                    return;
                }
                var field = resolve(fieldRef);
                if (field == null || invalidFields.contains(field)) {
                    return;
                }
                if (fieldValues.containsKey(field) || !method.getDescriptor().equals(CLINIT)
                        || !cls.getName().equals(field.getClassName()) || !isCandidateField(field)) {
                    invalidFields.add(field);
                    return;
                }
                if (writableProgram == null) {
                    writableProgram = ProgramUtils.copy(program);
                }
                var constant = evaluate(writableProgram, writableProgram.variableAt(value.getIndex()));
                if (constant == null) {
                    invalidFields.add(field);
                } else {
                    fieldValues.put(field, constant);
                }
            }
        };
        for (var i = 0; i < program.basicBlockCount(); ++i) {
            program.basicBlockAt(i).readAllInstructions(reader);
        }
    }

    private boolean isCandidateField(FieldReference fieldRef) {
        var cls = classSource.get(fieldRef.getClassName());
        if (cls == null) {
            return false;
        }
        var field = cls.getField(fieldRef.getFieldName());
        return field != null && field.hasModifier(ElementModifier.STATIC)
                && field.hasModifier(ElementModifier.FINAL)
                && field.getType() == ValueType.BOOLEAN;
    }

    private Integer evaluate(Program program, Variable value) {
        var definitions = new Instruction[program.variableCount()];
        var phiDefinitions = new Phi[program.variableCount()];
        var defExtractor = new DefinitionExtractor();
        for (var block : program.getBasicBlocks()) {
            for (var phi : block.getPhis()) {
                phiDefinitions[phi.getReceiver().getIndex()] = phi;
            }
            for (var insn : block) {
                insn.acceptVisitor(defExtractor);
                for (var defined : defExtractor.getDefinedVariables()) {
                    definitions[defined.getIndex()] = insn;
                }
            }
        }

        if (isAssertionStatus(definitions[value.getIndex()])) {
            return 0;
        }
        // Recognize the shape javac produces for `!desiredAssertionStatus()`:
        // a branch on the result of desiredAssertionStatus, each of two paths produces a constant,
        // and the join point receives them in a phi.
        var phi = phiDefinitions[value.getIndex()];
        if (phi == null || phi.getIncomings().size() != 2) {
            return null;
        }

        var first = phi.getIncomings().get(0).getSource();
        var second = phi.getIncomings().get(1).getSource();
        if (first == second || first.getIndex() == 0 || second.getIndex() == 0) {
            return null;
        }
        // Find the branch on the result of desiredAssertionStatus which leads to both paths,
        // and make sure that nothing else jumps into these paths.
        BranchingInstruction branch = null;
        var transitionExtractor = new TransitionExtractor();
        for (var block : program.getBasicBlocks()) {
            for (var tryCatch : block.getTryCatchBlocks()) {
                if (tryCatch.getHandler() == first || tryCatch.getHandler() == second) {
                    return null;
                }
            }
            var last = block.getLastInstruction();
            if (branch == null && last instanceof BranchingInstruction candidate) {
                if (isAssertionStatus(definitions[candidate.getOperand().getIndex()])
                        && ((candidate.getConsequent() == first && candidate.getAlternative() == second)
                        || (candidate.getConsequent() == second && candidate.getAlternative() == first))) {
                    branch = candidate;
                    continue;
                }
            }
            if (last != null) {
                last.acceptVisitor(transitionExtractor);
                var targets = transitionExtractor.getTargets();
                if (targets != null) {
                    for (var target : targets) {
                        if (target == first || target == second) {
                            return null;
                        }
                    }
                }
            }
        }
        if (branch == null) {
            return null;
        }
        BasicBlock taken;
        switch (branch.getCondition()) {
            case EQUAL:
                taken = branch.getConsequent();
                break;
            case NOT_EQUAL:
                taken = branch.getAlternative();
                break;
            default:
                return null;
        }
        for (var incoming : phi.getIncomings()) {
            if (incoming.getSource() == taken) {
                return getConstant(definitions, incoming.getValue());
            }
        }
        return null;
    }

    private Integer getConstant(Instruction[] definitions, Variable variable) {
        var insn = definitions[variable.getIndex()];
        if (insn instanceof IntegerConstantInstruction) {
            return ((IntegerConstantInstruction) insn).getConstant();
        }
        return null;
    }

    private static boolean isAssertionStatus(Instruction insn) {
        return insn instanceof InvokeInstruction && ((InvokeInstruction) insn).getMethod().equals(ASSERTION_METHOD);
    }

    private FieldReference resolve(FieldReference field) {
        return resolvedFields.computeIfAbsent(field, f -> {
            FieldReader resolved = classSource.resolve(f);
            return Optional.ofNullable(resolved != null ? resolved.getReference() : null);
        }).orElse(null);
    }

    public Map<FieldReference, Integer> getFieldValues() {
        return fieldValues;
    }

    public void apply(Program program) {
        for (var block : program.getBasicBlocks()) {
            for (var insn : block) {
                if (insn instanceof InvokeInstruction invoke) {
                    if (invoke.getMethod().equals(ASSERTION_METHOD)) {
                        replaceWithConstant(invoke, invoke.getReceiver(), 0);
                    }
                } else if (insn instanceof GetFieldInstruction getField) {
                    if (getField.getInstance() != null || fieldValues.isEmpty()) {
                        continue;
                    }
                    var field = resolve(getField.getField());
                    var value = field != null ? fieldValues.get(field) : null;
                    if (value != null) {
                        replaceWithConstant(getField, getField.getReceiver(), value);
                    }
                }
            }
        }
    }

    private static void replaceWithConstant(Instruction insn, Variable receiver, int value) {
        if (receiver == null) {
            insn.delete();
        } else {
            var replacement = new IntegerConstantInstruction();
            replacement.setConstant(value);
            replacement.setReceiver(receiver);
            replacement.setLocation(insn.getLocation());
            insn.replace(replacement);
        }
    }
}
