package org.teavm.classlib.impl;

import java.util.ListResourceBundle;
import java.util.ResourceBundle;

/**
 * Bodies of native methods are generated by {@link ResourceBundleTransformer}.
 */
public final class ResourceBundleImpl {
    private ResourceBundleImpl() {
    }

    public static native String[] bundleNames();

    public static native ResourceBundle createBundle(int index);

    static ResourceBundle createPropertiesBundle(String[] keysAndValues) {
        var contents = new Object[keysAndValues.length / 2][];
        for (var i = 0; i < contents.length; ++i) {
            contents[i] = new Object[] { keysAndValues[i * 2], keysAndValues[i * 2 + 1] };
        }
        return new PropertiesBundle(contents);
    }

    static class PropertiesBundle extends ListResourceBundle {
        private Object[][] contents;

        PropertiesBundle(Object[][] contents) {
            this.contents = contents;
        }

        @Override
        protected Object[][] getContents() {
            return contents;
        }
    }
}
